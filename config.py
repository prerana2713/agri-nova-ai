import os
import secrets
from pathlib import Path
from dotenv import load_dotenv

BASE_DIR = Path(__file__).resolve().parent
load_dotenv(BASE_DIR / ".env")

INSTANCE_DIR = BASE_DIR / "instance"
INSTANCE_DIR.mkdir(exist_ok=True)


def _get_or_create_secret_key() -> str:
    env_key = os.environ.get("SECRET_KEY", "").strip()
    if env_key:
        return env_key
    secret_file = INSTANCE_DIR / ".secret_key"
    if secret_file.exists():
        stored = secret_file.read_text(encoding="utf-8").strip()
        if stored:
            return stored
    generated = secrets.token_hex(32)
    secret_file.write_text(generated, encoding="utf-8")
    return generated


class Config:
    SECRET_KEY = _get_or_create_secret_key()
    SQLALCHEMY_DATABASE_URI = os.environ.get(
        "DATABASE_URL",
        f"sqlite:///{(INSTANCE_DIR / 'agri_nova.db').as_posix()}",
    )
    SQLALCHEMY_TRACK_MODIFICATIONS = False

    SESSION_COOKIE_HTTPONLY = True
    SESSION_COOKIE_SAMESITE = "Lax"

    MODEL_PATH = str(BASE_DIR / "ml_model" / "fertilizer_model.pkl")
    DATASET_PATH = str(BASE_DIR / "ml_model" / "cleaned_fertilizer_dataset.csv")
    LEGACY_HISTORY_PATH = str(BASE_DIR / "history.json")

    OPENWEATHER_API_KEY = os.environ.get("OPENWEATHER_API_KEY", "").strip()
    WEATHER_TIMEOUT_SECONDS = 8
    IOT_DEVICE_TOKEN = os.environ.get("IOT_DEVICE_TOKEN", "").strip()

    CROP_MAPPING = {
        "Rice": "Paddy",
        "Wheat": "Wheat",
        "Maize": "Maize",
        "Cotton": "Cotton",
        "Sugarcane": "Sugarcane",
        "Groundnut": "Ground Nuts",
    }

    ALLOWED_SOILS = ["Sandy", "Loamy", "Black", "Red", "Clayey"]

    CROP_TARGETS = {
        "Rice": (100, 40, 40),
        "Wheat": (120, 60, 40),
        "Maize": (120, 60, 50),
        "Cotton": (100, 50, 50),
        "Sugarcane": (150, 60, 60),
        "Groundnut": (25, 50, 50),
    }

    PROTOTYPE_DISCLAIMER = (
        "The fertilizer prediction is generated by a Random Forest model trained on a "
        "small 99-record educational dataset. Its output is an academic prototype and has "
        "not been validated for real-world farm prescriptions. Nutrient thresholds and "
        "match scores are illustrative only. Always confirm fertilizer selection and "
        "application rates with a certified soil laboratory or qualified agronomist."
    )
